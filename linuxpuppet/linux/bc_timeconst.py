#!/usr/bin/env python3
"""Stand-in for `bc -q kernel/time/timeconst.bc` """
import sys
from math import gcd

args = [a for a in sys.argv[1:] if a != "-q"]
if len(args) != 1 or not args[0].endswith("timeconst.bc"):
    sys.exit("bc_timeconst.py: only kernel/time/timeconst.bc is supported")
hz = int(sys.stdin.read().split()[0])

fmul = lambda b, n, d: (2 ** b * n + d - 1) // d
def fadj(b, n, d):
    d = d // gcd(n, d)
    return 2 ** b * (d - 1) // d
def fmuls(b, n, d):
    s = 0
    while fmul(s, n, d) < 2 ** (b - 1):
        s += 1
    return s

o = []
p = o.append
p("/* Automatically generated by kernel/time/timeconst.bc */\n")
p("/* Time conversion constants for HZ == %d */\n" % hz)
p("\n#ifndef KERNEL_TIMECONST_H\n#define KERNEL_TIMECONST_H\n\n")
p("#include <linux/param.h>\n#include <linux/types.h>\n\n")
p("#if HZ != %d\n#error \"include/generated/timeconst.h has the wrong HZ value!\"\n#endif\n\n" % hz)
if hz < 2:
    p("#error Totally bogus HZ value!\n")
else:
    s = fmuls(32, 1000, hz)
    p("#define HZ_TO_MSEC_MUL32\tU64_C(0x%X)\n" % fmul(s, 1000, hz))
    p("#define HZ_TO_MSEC_ADJ32\tU64_C(0x%X)\n" % fadj(s, 1000, hz))
    p("#define HZ_TO_MSEC_SHR32\t%d\n" % s)
    s = fmuls(32, hz, 1000)
    p("#define MSEC_TO_HZ_MUL32\tU64_C(0x%X)\n" % fmul(s, hz, 1000))
    p("#define MSEC_TO_HZ_ADJ32\tU64_C(0x%X)\n" % fadj(s, hz, 1000))
    p("#define MSEC_TO_HZ_SHR32\t%d\n" % s)
    cd = gcd(hz, 1000)
    p("#define HZ_TO_MSEC_NUM\t\t%d\n#define HZ_TO_MSEC_DEN\t\t%d\n" % (1000 // cd, hz // cd))
    p("#define MSEC_TO_HZ_NUM\t\t%d\n#define MSEC_TO_HZ_DEN\t\t%d\n\n" % (hz // cd, 1000 // cd))
    s = fmuls(32, 1000000, hz)
    p("#define HZ_TO_USEC_MUL32\tU64_C(0x%X)\n" % fmul(s, 1000000, hz))
    p("#define HZ_TO_USEC_ADJ32\tU64_C(0x%X)\n" % fadj(s, 1000000, hz))
    p("#define HZ_TO_USEC_SHR32\t%d\n" % s)
    s = fmuls(32, hz, 1000000)
    p("#define USEC_TO_HZ_MUL32\tU64_C(0x%X)\n" % fmul(s, hz, 1000000))
    p("#define USEC_TO_HZ_ADJ32\tU64_C(0x%X)\n" % fadj(s, hz, 1000000))
    p("#define USEC_TO_HZ_SHR32\t%d\n" % s)
    cd = gcd(hz, 1000000)
    p("#define HZ_TO_USEC_NUM\t\t%d\n#define HZ_TO_USEC_DEN\t\t%d\n" % (1000000 // cd, hz // cd))
    p("#define USEC_TO_HZ_NUM\t\t%d\n#define USEC_TO_HZ_DEN\t\t%d\n" % (hz // cd, 1000000 // cd))
    cd = gcd(hz, 1000000000)
    p("#define HZ_TO_NSEC_NUM\t\t%d\n#define HZ_TO_NSEC_DEN\t\t%d\n" % (1000000000 // cd, hz // cd))
    p("#define NSEC_TO_HZ_NUM\t\t%d\n#define NSEC_TO_HZ_DEN\t\t%d\n\n" % (hz // cd, 1000000000 // cd))
    p("#endif /* KERNEL_TIMECONST_H */\n")
sys.stdout.write("".join(o))
